// ── Lookup sets (built at startup, O(1) checks) ───────────────
const WH_WORD_SET = new Set(WH_WORDS_RAW);

const WH_PREFIX_SET = new Set();
for (const w of WH_WORDS_RAW) {
  for (let i = 1; i <= w.length; i++) {
    WH_PREFIX_SET.add(w.slice(0, i));
  }
}

// ── Helpers ───────────────────────────────────────────────────
function whIsValidWord(w)  { return WH_WORD_SET.has(w); }
function whIsPrefix(p)     { return WH_PREFIX_SET.has(p); }
function whScore(len) {
  if (len < 3) return 0;
  const table = [0, 0, 0, 100, 400, 800, 1400, 1800];
  return len < table.length ? table[len] : 2200;
}